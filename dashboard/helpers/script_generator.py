from datetime import datetime
from app import __appName__, __appVersion__, __appDescription__, __appAuthor__
from pySerialX.version import __version__, __app_name__, __author__
from dataclasses import dataclass

@dataclass
class ScriptData:
    led_state: bool

def generate_python_script(data: ScriptData, port: str, baudrate: str) -> str:
    if data is None:
        raise ValueError("Data cannot be None")

    now = datetime.now()
    lines = []

    # App info
    lines.append(f"#!python3")
    lines.append(f"// Generated by {__app_name__} v{__version__} by {__author__} at {now.strftime('%d/%m/%Y %H:%M:%S')}")
    lines.append("")
    lines.append("from pySerialX.python_integration import SerialX")
    lines.append("")    
    lines.append(f"SerialXInstance = SerialX(\"{port}\", \"{baudrate}\")")
    lines.append(f"SerialXInstance.set(bool, \"led_state\", {data.led_state})")
    lines.append("")

    script = "\n".join(lines)

    return script

